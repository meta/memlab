/**
 * Generate the README's tool tables, and the website's tool reference pages
 * (one page per group, in `website/docs/mcp-server/tools/`), from
 * `src/tools/tools-index.ts`.
 *
 * The index is what `memlab_tools` prints in a session; the README tables
 * were a hand-kept copy of it, and a copy drifts: a tool added to one and not
 * the other is documented in one place and invisible in the other. The index
 * is the single source now.
 *
 *   node scripts/sync-tool-catalog.mjs          rewrite README.md and the pages
 *   node scripts/sync-tool-catalog.mjs --check  fail if either is stale
 */
import fs from 'fs';
import path from 'path';
import {fileURLToPath} from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const indexFile = path.join(here, '..', 'src', 'tools', 'tools-index.ts');
const readmeFile = path.join(here, '..', 'README.md');
const END_MARKER = '## Core Session Tools';
// absent outside the memlab repo (e.g. in the published package)
const websiteDocsDir = path.join(here, '..', '..', '..', 'website', 'docs');
const toolPagesDir = path.join(websiteDocsDir, 'mcp-server', 'tools');
// the page that lists the groups, between these two lines
const toolIndexFile = path.join(websiteDocsDir, 'mcp-server', 'tools.md');
const GROUP_TABLE_START =
  '<!-- tool groups: generated by `npm run sync-catalog` in packages/mcp-server -->';
const GROUP_TABLE_END = '<!-- end of tool groups -->';
// the sidebar label of each group's page
const PAGE_LABELS = {
  composition: 'Heap composition',
  growth: 'Growth and leaks',
  retention: 'Retention',
  artifacts: 'Measurement artifacts',
  dom: 'Detached DOM and listeners',
  collections: 'Collections and caches',
  strings: 'Strings and duplication',
  inspect: 'Inspect objects',
  ask: 'Custom queries',
  sharing: 'Sharing a capture',
  session: 'Session and batching',
};

function readGroups() {
  const src = fs.readFileSync(indexFile, 'utf8');
  const open = 'const GROUPS: Group[] = [';
  const start = src.indexOf(open);
  const end = src.indexOf('\n];', start);
  if (start < 0 || end < 0) {
    throw new Error('sync-tool-catalog: could not find the GROUPS literal.');
  }
  // The literal is plain data (strings, arrays, objects), so it evaluates as
  // JavaScript once the TypeScript annotation is gone.
  const body = src.slice(start + open.length, end);
  try {
    return new Function(`return [${body}];`)();
  } catch (err) {
    throw new Error(
      `sync-tool-catalog: the GROUPS literal in tools-index.ts did not evaluate (${err.message}). It must be plain data, closed by a line that starts with "];".`,
    );
  }
}

function render(groups) {
  const cell = text => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ');
  return groups
    .map(g =>
      [
        `### ${g.question}`,
        '',
        '| Tool | Use it when |',
        '| --- | --- |',
        ...g.tools.map(([name, when]) => `| \`${name}\` | ${cell(when)} |`),
        '',
      ].join('\n'),
    )
    .join('\n');
}

// MDX reads `{` and `<` outside code spans as JSX
function escapeMdx(text) {
  return text
    .split('`')
    .map((part, i) =>
      i % 2 === 1 ? part : part.replace(/[{}]/g, '\\$&').replace(/</g, '&lt;'),
    )
    .join('`');
}

function renderPage(group, position) {
  const label = PAGE_LABELS[group.key];
  if (label == null) {
    throw new Error(
      `sync-tool-catalog: add a sidebar label for the "${group.key}" group to PAGE_LABELS.`,
    );
  }
  const cell = text =>
    escapeMdx(text.replace(/\|/g, '\\|').replace(/\s+/g, ' '));
  return [
    '---',
    `title: ${JSON.stringify(group.question)}`,
    `description: ${JSON.stringify(group.question)}`,
    `sidebar_label: ${label}`,
    `sidebar_position: ${position}`,
    'custom_edit_url: null',
    '---',
    '',
    `These tools are in the \`${group.key}\` toolset. Starting the server with`,
    `\`MEMLAB_TOOLSETS=${group.key}\` exposes only them, plus the few tools every`,
    `session needs, and \`memlab_tools({enable: "${group.key}"})\` turns them on`,
    'in a session. Try them in the order listed.',
    '',
    '| Tool | Use it when |',
    '| --- | --- |',
    ...group.tools.map(([name, when]) => `| \`${name}\` | ${cell(when)} |`),
    '',
  ].join('\n');
}

// file name → content of every tool reference page
function renderPages(groups) {
  return new Map(
    groups.map((group, i) => [`${group.key}.md`, renderPage(group, i + 1)]),
  );
}

// the tool index page, with its table of groups regenerated
function renderGroupTable(groups) {
  const index = fs.readFileSync(toolIndexFile, 'utf8');
  const start = index.indexOf(`${GROUP_TABLE_START}\n`);
  const end = index.indexOf(`${GROUP_TABLE_END}\n`, start);
  if (start < 0 || end < 0) {
    throw new Error(
      `sync-tool-catalog: ${toolIndexFile} needs a "${GROUP_TABLE_START}" line followed by "${GROUP_TABLE_END}".`,
    );
  }
  const rows = groups.map(
    group =>
      `| [${PAGE_LABELS[group.key]}](./tools/${group.key}.md) | ` +
      `${escapeMdx(group.question)} | ${group.tools.length} |`,
  );
  const table = [
    GROUP_TABLE_START,
    '',
    '| Group | Answers | Tools |',
    '| --- | --- | --- |',
    ...rows,
    '',
    '',
  ].join('\n');
  return index.slice(0, start) + table + index.slice(end);
}

// the names of the pages that differ from `pages`, including stray ones
function stalePages(pages) {
  const existing = fs.existsSync(toolPagesDir)
    ? fs.readdirSync(toolPagesDir).filter(file => file.endsWith('.md'))
    : [];
  const stale = existing.filter(file => !pages.has(file));
  for (const [file, content] of pages) {
    const filePath = path.join(toolPagesDir, file);
    if (
      !fs.existsSync(filePath) ||
      fs.readFileSync(filePath, 'utf8') !== content
    ) {
      stale.push(file);
    }
  }
  return stale;
}

const groups = readGroups();
const pages = fs.existsSync(websiteDocsDir) ? renderPages(groups) : null;
const toolIndex = pages == null ? null : renderGroupTable(groups);
const readme = fs.readFileSync(readmeFile, 'utf8');
const first = `### ${groups[0].question}`;
// Whole lines only: the same words in prose must not move the splice.
const lineAt = (line, from) => {
  const i = readme.indexOf(`\n${line}\n`, from - 1);
  return i < 0 ? -1 : i + 1;
};
const start = lineAt(first, 0);
const end = start < 0 ? -1 : lineAt(END_MARKER, start);
if (start < 0 || end < 0) {
  console.error(
    `sync-tool-catalog: README.md needs a "${first}" heading followed by "${END_MARKER}".`,
  );
  process.exit(1);
}
const next = readme.slice(0, start) + render(groups) + readme.slice(end);

if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error(
      'sync-tool-catalog: README.md tool tables differ from src/tools/tools-index.ts. Run `node scripts/sync-tool-catalog.mjs`.',
    );
    process.exit(1);
  }
  const stale = pages == null ? [] : stalePages(pages);
  if (
    toolIndex != null &&
    toolIndex !== fs.readFileSync(toolIndexFile, 'utf8')
  ) {
    stale.push('../tools.md');
  }
  if (stale.length > 0) {
    console.error(
      `sync-tool-catalog: website tool pages differ from src/tools/tools-index.ts (${stale.join(', ')}). Run \`node scripts/sync-tool-catalog.mjs\`.`,
    );
    process.exit(1);
  }
  const count = groups.reduce((s, g) => s + g.tools.length, 0);
  console.log(
    `sync-tool-catalog: README.md tool tables match the index (${groups.length} groups, ${count} rows).`,
  );
} else {
  fs.writeFileSync(readmeFile, next);
  console.log('sync-tool-catalog: README.md tool tables regenerated.');
  if (pages != null) {
    fs.rmSync(toolPagesDir, {recursive: true, force: true});
    fs.mkdirSync(toolPagesDir, {recursive: true});
    for (const [file, content] of pages) {
      fs.writeFileSync(path.join(toolPagesDir, file), content);
    }
    fs.writeFileSync(toolIndexFile, toolIndex);
    console.log(
      `sync-tool-catalog: ${pages.size} website tool pages regenerated.`,
    );
  }
}
